REQUIRED_FEATURE_MAP = {
    "hours_studied": "Hours Studied",
    "previous_scores": "Previous Scores",
    "extracurricular_activities": "Extracurricular Activities",
    "sleep_hours": "Sleep Hours",
    "sample_question_papers_practiced": "Sample Question Papers Practiced",
}


def validate_prediction_input(data: Any) -> Tuple[Optional[Dict[str, Any]], Optional[str]]:
    """
    Validate and extract the 5 student input features.
    Supports both snake_case and exact dataset column names.
    Returns (cleaned_dict, None) on success or (None, error_message) on failure.
    """
    if not isinstance(data, dict):
        return None, "Request payload must be a JSON object."

    cleaned: Dict[str, Any] = {}

    # 1. Hours Studied (0 <= x <= 24)
    raw_hours = data.get("hours_studied", data.get("Hours Studied"))
    if raw_hours is None:
        return None, "Missing required field: 'hours_studied' (or 'Hours Studied')."
    try:
        hours_val = float(raw_hours)
    except (ValueError, TypeError):
        return None, "'hours_studied' must be a valid number."
    if not (0 <= hours_val <= 24):
        return None, f"'hours_studied' must be between 0 and 24 (received: {hours_val})."
    cleaned["Hours Studied"] = hours_val

    # 2. Previous Scores (0 <= x <= 100)
    raw_scores = data.get("previous_scores", data.get("Previous Scores"))
    if raw_scores is None:
        return None, "Missing required field: 'previous_scores' (or 'Previous Scores')."
    try:
        score_val = float(raw_scores)
    except (ValueError, TypeError):
        return None, "'previous_scores' must be a valid number."
    if not (0 <= score_val <= 100):
        return None, f"'previous_scores' must be between 0 and 100 (received: {score_val})."
    cleaned["Previous Scores"] = score_val

    # 3. Extracurricular Activities ('Yes' or 'No')
    raw_extra = data.get("extracurricular_activities", data.get("Extracurricular Activities"))
    if raw_extra is None:
        return None, "Missing required field: 'extracurricular_activities' (or 'Extracurricular Activities')."
    if not isinstance(raw_extra, str):
        return None, "'extracurricular_activities' must be a string ('Yes' or 'No')."
    norm_extra = raw_extra.strip().capitalize()
    if norm_extra not in ["Yes", "No"]:
        return None, f"'extracurricular_activities' must be either 'Yes' or 'No' (received: '{raw_extra}')."
    cleaned["Extracurricular Activities"] = norm_extra

    # 4. Sleep Hours (0 <= x <= 24)
    raw_sleep = data.get("sleep_hours", data.get("Sleep Hours"))
    if raw_sleep is None:
        return None, "Missing required field: 'sleep_hours' (or 'Sleep Hours')."
    try:
        sleep_val = float(raw_sleep)
    except (ValueError, TypeError):
        return None, "'sleep_hours' must be a valid number."
    if not (0 <= sleep_val <= 24):
        return None, f"'sleep_hours' must be between 0 and 24 (received: {sleep_val})."
    cleaned["Sleep Hours"] = sleep_val

    # 5. Sample Question Papers Practiced (x >= 0)
    raw_papers = data.get("sample_question_papers_practiced", data.get("Sample Question Papers Practiced"))
    if raw_papers is None:
        return None, "Missing required field: 'sample_question_papers_practiced' (or 'Sample Question Papers Practiced')."
    try:
        papers_val = float(raw_papers)
    except (ValueError, TypeError):
        return None, "'sample_question_papers_practiced' must be a valid number."
    if papers_val < 0:
        return None, f"'sample_question_papers_practiced' cannot be negative (received: {papers_val})."
    cleaned["Sample Question Papers Practiced"] = papers_val

    return cleaned, None


def get_driving_factors(inputs: Dict[str, Any], prediction: float) -> list[Dict[str, Any]]:
    """Estimate which student behaviors are most influencing the predicted score."""
    factors = []
    feature_specs = [
        ("Hours Studied", "Hours Studied", 7.0, 2.0, 10.0),
        ("Previous Scores", "Previous Scores", 80.0, 40.0, 100.0),
        ("Sleep Hours", "Sleep Hours", 7.5, 5.0, 9.0),
        ("Sample Question Papers Practiced", "Sample Question Papers Practiced", 5.0, 0.0, 10.0),
        ("Extracurricular Activities", "Extracurricular Activities", 1.0, 0.0, 1.0),
    ]

    for label, key, target, minimum, maximum in feature_specs:
        value = inputs.get(key, 0)
        if key == "Extracurricular Activities":
            current = 1 if str(value).lower() == "yes" else 0
            score = 0 if current == 0 else 10
            impact = round((current - 0.5) * 12.0, 1)
            factors.append({
                "feature": label,
                "summary": "Extra-curricular engagement" if current else "Limited engagement outside class",
                "impact": impact,
            })
            continue

        normalized = (value - minimum) / (maximum - minimum) if maximum > minimum else 0
        normalized = max(0.0, min(1.0, normalized))
        score_carry = (normalized * 100.0) - 50.0
        impact = round(score_carry * 0.2, 1)

        if value < target:
            direction = "Below target"
        elif value > target:
            direction = "Above target"
        else:
            direction = "At target"

        factors.append({
            "feature": label,
            "summary": direction,
            "impact": impact,
        })

    factors.sort(key=lambda item: abs(item["impact"]), reverse=True)
    return factors[:3]


def get_recommendations(inputs: Dict[str, Any], prediction: float) -> list[str]:
    """Generate concise, actionable recommendations from the student's profile."""
    recos = []
    hours = float(inputs.get("Hours Studied", 0))
    scores = float(inputs.get("Previous Scores", 0))
    sleep = float(inputs.get("Sleep Hours", 0))
    papers = float(inputs.get("Sample Question Papers Practiced", 0))
    extracurricular = str(inputs.get("Extracurricular Activities", "No"))

    if hours < 5:
        recos.append("Increase daily study time to 5–6 focused hours and break revision into two timed sessions.")
    elif hours >= 7:
        recos.append("Your study rhythm is strong — keep the same routine and protect it from burnout.")

    if scores < 65:
        recos.append("Revisit foundational concepts and add short topic-wise quizzes to improve accuracy and confidence.")
    elif scores >= 85:
        recos.append("Maintain your strong academic base and challenge yourself with advanced problem sets.")

    if sleep < 6.5:
        recos.append("Aim for 7–8 hours of sleep nightly; better rest will improve retention and exam stamina.")
    elif sleep >= 7 and sleep <= 9:
        recos.append("Your sleep schedule supports learning well; keep it consistent before tests and deadlines.")

    if papers < 3:
        recos.append("Solve 2–3 more timed mock papers each week to build speed, accuracy, and exam confidence.")
    else:
        recos.append("Your practice-paper routine is healthy; keep reviewing mistakes to turn them into stronger scores.")

    if str(extracurricular).lower() != "yes":
        recos.append("Try one regular activity like sports, music, or debate to reduce stress and improve balance.")

    if not recos:
        recos.append("Keep a consistent study plan, review mistakes weekly, and continue building strong habits.")

    return recos[:4]


