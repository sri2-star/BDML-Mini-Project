app = Flask(__name__)

# ==============================================================================
# Model Configuration & Loader
# ==============================================================================
MODEL_CANDIDATE_PATHS = [
    Path("model") / "trained_model.pkl",           # Primary requested path
    Path("models") / "trained_model.pkl",          # Alternate pickle path
    Path("models") / "best_model_pipeline.joblib", # Pipeline generated by train_model.py
    Path("model") / "best_model_pipeline.joblib",
]

_model = None
_loaded_model_path: Optional[str] = None


def load_trained_model():
    """
    Load the trained ML pipeline from disk.
    Searches primary and fallback candidate paths.
    """
    global _model, _loaded_model_path
    for candidate in MODEL_CANDIDATE_PATHS:
        if candidate.exists():
            try:
                _model = joblib.load(candidate)
                _loaded_model_path = str(candidate.resolve())
                print(f"[EduPredict] Successfully loaded ML pipeline from: {_loaded_model_path}")
                return _model
            except Exception as e:
                print(f"[EduPredict] Warning: Failed to load candidate {candidate}: {e}")
    print("[EduPredict] Notice: No trained model found at candidate paths. /predict will return 503 until trained.")
    return None


# Attempt loading on module load
load_trained_model()


